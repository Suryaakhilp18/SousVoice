    t = t.replace(/Sauté onions, garlic, and aromatics for (\d+(?:\s*to\s*\d+)?)\s*minutes? until soft and fragrant\./i, 'ఉల్లిపాయలు, వెల్లుల్లి వేసి మంచి వాసన వచ్చే వరకు $1 నిమిషాలు వేయించండి.');
